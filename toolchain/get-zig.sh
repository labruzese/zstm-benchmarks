#!/usr/bin/env bash
#
# Install the Zig toolchain used by this benchmark.
#
# We pull Zig from PyPI rather than ziglang.org: the `ziglang` wheel bundles the
# real upstream toolchain, and PyPI is reachable from environments where
# ziglang.org is not. Version 0.16.0 is what zstm's build.zig.zon declares as
# its `minimum_zig_version`.
#
# After running this, use `toolchain/zig` as the zig binary.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"
VENV="$ROOT/.venv"
ZIG_VERSION="0.16.0"

if [ ! -d "$VENV" ]; then
    python3 -m venv "$VENV"
fi

"$VENV/bin/pip" install --quiet --disable-pip-version-check "ziglang==$ZIG_VERSION"

cat > "$HERE/zig" <<EOF
#!/usr/bin/env bash
# Generated by get-zig.sh -- thin shim over the PyPI-installed Zig toolchain.
exec "$VENV/bin/python" -m ziglang "\$@"
EOF
chmod +x "$HERE/zig"

echo "zig $("$HERE/zig" version) installed at $HERE/zig"
